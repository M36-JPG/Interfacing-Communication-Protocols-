/* =========================================================
   Read DIP
   ========================================================= */

uint8_t DIP_Read(void)
{
    /*
     * Hardware:
     *
     * Switch ON  = PIN 0
     * Switch OFF = PIN 1
     *
     * Convert:
     *
     * ON  = 1
     * OFF = 0
     */

    return ((~PINC) & DIP_MASK);
}


