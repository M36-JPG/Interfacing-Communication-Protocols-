/* =========================================================
   Buttons Initialization
   ========================================================= */

void Buttons_Init(void)
{
    /*
     * B1 = PD2
     * B2 = PD3
     */

    DDRD &= ~(1 << B1_PIN);
    DDRD &= ~(1 << B2_PIN);


    /*
     * Internal Pull-ups
     */

    PORTD |= (1 << B1_PIN);
    PORTD |= (1 << B2_PIN);
}


/* =========================================================
   Read B1
   ========================================================= */

uint8_t B1_Read(void)
{
    /*
     * Released = 1
     * Pressed  = 0
     */

    return ((PIND >> B1_PIN) & 1);
}


/* =========================================================
   Read B2
   ========================================================= */

uint8_t B2_Read(void)
{
    /*
     * Released = 1
     * Pressed  = 0
     */

    return ((PIND >> B2_PIN) & 1);
}


